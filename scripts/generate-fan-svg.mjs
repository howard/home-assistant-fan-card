// Generates the Noctua-style beige fan SVG into src/fan-svg.js.
// Parametric blade geometry tuned to the Noctua NF-A-series frontal look:
// 7 blades that nearly fill the 51.4° slot (thin tip slits), widest at a
// "shoulder" ~75% of span, tip swept slightly behind the shoulder, roots
// tucked under the hub disc.
// Iterate on the parameters below, run `npm run gen:svg`, and look at
// demo/svg-preview.html.
import { writeFileSync } from "node:fs";

const NUM_BLADES = 7;
const SLOT = 360 / NUM_BLADES; // 51.43°
const R_ROOT = 17; // blade root radius (under the hub disc)
const R_TIP = 45.4; // blade tip radius (hole is 46.5)
const HUB_R = 18.5; // hub disc covers blade roots

const deg = (d) => (d * Math.PI) / 180;
const pt = (r, a, cx = 50, cy = 50) => [
  cx + r * Math.cos(deg(a)),
  cy + r * Math.sin(deg(a)),
];
const fmt = (v) => v.toFixed(2);

// One swept impeller blade, relative to the blade center (0°).
// Angles clockwise-positive (SVG y is down).
//   root leading   (R_ROOT, +4°)   ->  leading edge  -> tip (+24°)
//   tip           (+24°..-13°)     -> rounded
//   tip trailing  (44.5, -13°)     -> trailing edge -> root trailing (-22°)
//   root arc       back to root leading
function bladePath() {
  const rl = pt(R_ROOT, 4); // root leading
  const rt = pt(R_ROOT, -22); // root trailing
  const tl = pt(R_TIP, 24); // tip leading
  const tt = pt(R_TIP - 1, -13); // tip trailing

  // Leading edge: convex shoulder bulge at ~75% span, tip slightly behind it.
  const le1 = pt(26, 18);
  const le2 = pt(38, 26.5);
  // Rounded tip, slightly bulging past the leading/trailing tip points.
  const tip = pt(R_TIP + 1.6, 5.5);
  // Trailing edge: gentle concave sweep back to the root.
  const te1 = pt(40, -16.5);
  const te2 = pt(28, -20);

  const d = [
    `M ${fmt(rl[0])} ${fmt(rl[1])}`,
    `C ${fmt(le1[0])} ${fmt(le1[1])}, ${fmt(le2[0])} ${fmt(le2[1])}, ${fmt(tl[0])} ${fmt(tl[1])}`,
    `Q ${fmt(tip[0])} ${fmt(tip[1])}, ${fmt(tt[0])} ${fmt(tt[1])}`,
    `C ${fmt(te1[0])} ${fmt(te1[1])}, ${fmt(te2[0])} ${fmt(te2[1])}, ${fmt(rt[0])} ${fmt(rt[1])}`,
    `A ${R_ROOT} ${R_ROOT} 0 0 1 ${fmt(rl[0])} ${fmt(rl[1])}`,
    "Z",
  ].join(" ");
  return d;
}

function fanSvg() {
  const blades = [];
  for (let i = 0; i < NUM_BLADES; i++) {
    const rot = SLOT * i;
    blades.push(
      `<g transform="rotate(${rot} 50 50)"><path d="${bladePath()}" fill="#7a5734"/></g>`
    );
  }
  return blades.join("\n    ");
}

const svg = `// Generated by scripts/generate-fan-svg.mjs — do not edit by hand.
export const FAN_SVG = \`<svg viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg">
  <!-- frame: rounded square with circular opening (evenodd cutout) -->
  <path fill="#d9cdb2" d="M 5 0 L 95 0 A 5 5 0 0 1 100 5 L 100 95 A 5 5 0 0 1 95 100 L 5 100 A 5 5 0 0 1 0 95 L 0 5 A 5 5 0 0 1 5 0 Z M 50 3.5 A 46.5 46.5 0 1 0 50 96.5 A 46.5 46.5 0 1 0 50 3.5 Z" fill-rule="evenodd"/>
  <!-- opening rim -->
  <circle cx="50" cy="50" r="46.5" fill="none" stroke="#bfae88" stroke-width="1.5"/>
  <!-- corner screws -->
  <circle cx="9" cy="9" r="2.2" fill="#a9986f"/>
  <circle cx="91" cy="9" r="2.2" fill="#a9986f"/>
  <circle cx="9" cy="91" r="2.2" fill="#a9986f"/>
  <circle cx="91" cy="91" r="2.2" fill="#a9986f"/>
  <!-- rotating assembly -->
  <g class="fan-rotor">
    ${fanSvg()}
    <circle cx="50" cy="50" r="${HUB_R}" fill="#d5c7a6"/>
    <circle cx="50" cy="50" r="${HUB_R}" fill="none" stroke="#a08d64" stroke-width="1.2"/>
    <circle cx="50" cy="50" r="8.5" fill="none" stroke="#a08d64" stroke-width="1.2"/>
    <circle cx="50" cy="50" r="2.6" fill="#8a764f"/>
  </g>
</svg>\`;`;

writeFileSync(new URL("../src/fan-svg.js", import.meta.url), svg);
console.log("wrote src/fan-svg.js");
